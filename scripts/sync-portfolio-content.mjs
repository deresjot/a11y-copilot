import { cp, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const portfolio = resolve(root, "../deresjot-web/source/a11y-copilot");
const documentFiles = ["ACCESSIBILITY.md", "CHANGELOG.md", "README.md", "SKILL.md", "TUTORIAL.md"];
const documentFolders = ["patterns", "references"];

for (const file of documentFiles) await cp(resolve(root, file), resolve(portfolio, file));
for (const folder of documentFolders) {
  await mkdir(resolve(portfolio, folder), { recursive: true });
  await cp(resolve(root, folder), resolve(portfolio, folder), { recursive: true, force: true });
}

const markdownFiles = [];
for (const folder of ["", ...documentFolders]) {
  for (const entry of await readdir(resolve(root, folder), { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".md")) markdownFiles.push(relative(root, resolve(root, folder, entry.name)).replaceAll("\\", "/"));
  }
}
markdownFiles.sort();
const documents = Object.fromEntries(await Promise.all(markdownFiles.map(async file => [file, await readFile(resolve(root, file), "utf8")])));
const bundle = `/* Generated by scripts/build-markdown-bundle.mjs. Do not edit directly. */\nwindow.A11Y_MARKDOWN_CONTENT = ${JSON.stringify(documents)};\n`;
await writeFile(resolve(root, "assets/markdown-content.js"), bundle);
await writeFile(resolve(portfolio, "assets/markdown-content.js"), bundle);
console.log(`Portfolio-Inhalte synchronisiert: ${markdownFiles.length} Markdown-Dateien.`);
